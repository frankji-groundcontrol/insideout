// rv4-FEAT-02: accepting a proposal applies its items once. Real PostgreSQL
// (DATABASE_URL); the failure case also needs DATABASE_OWNER_URL, because
// poisoning one title is the only way to make the database itself refuse an
// insert part-way through an apply without a mock.

// applyFixture is a project whose owner filed an agent proposal carrying items.
type applyFixture struct {
	owner *User
	ws    *Workspace
	proj  *Project
	upd   *ProjectUpdate
}

func newApplyFixture(t *testing.T, st *Store, items ...ProposalItem) *applyFixture {
	t.Helper()
	ctx := context.Background()
	owner := mkUser(t, st)
	ws, err := st.CreateWorkspace(ctx, owner.ID, "Apply once WS", "")
	if err != nil {
		t.Fatalf("create workspace: %v", err)
	}
	proj, err := st.CreateProject(ctx, owner.ID, ws.ID, "Apply once", "")
	if err != nil {
		t.Fatalf("create project: %v", err)
	}
	upd, err := st.AddProjectUpdate(ctx, owner.ID, proj.ID, "agent_proposal", "[agent proposal/structure] apply once")
	if err != nil {
		t.Fatalf("add proposal: %v", err)
	}
	for i := range items {
		items[i].Action = "add_node"
	}
	if err := st.AddProposalItems(ctx, owner.ID, upd.ID, items); err != nil {
		t.Fatalf("add items: %v", err)
	}
	return &applyFixture{owner: owner, ws: ws, proj: proj, upd: upd}
}

// nodes returns the project's roadmap nodes keyed by title, failing on a title
// that appears twice: a second apply is exactly that.
func (f *applyFixture) nodes(t *testing.T, st *Store) (map[string]RoadmapNode, []string) {
	t.Helper()
	list, err := st.ListRoadmap(context.Background(), f.owner.ID, f.proj.ID)
	if err != nil {
		t.Fatalf("list roadmap: %v", err)
	}
	byTitle := map[string]RoadmapNode{}
	titles := make([]string, 0, len(list))
	for _, n := range list {
		byTitle[n.Title] = n
		titles = append(titles, n.Title)
	}
	sort.Strings(titles)
	return byTitle, titles
}

func (f *applyFixture) wantTitles(t *testing.T, st *Store, want ...string) map[string]RoadmapNode {
	t.Helper()
	byTitle, got := f.nodes(t, st)
	sort.Strings(want)
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Fatalf("roadmap nodes: got %q, want %q", got, want)
	}
	return byTitle
}

func TestProposalApply_SecondApplyCreatesNothing(t *testing.T) {
	st := newTestStore(t)
	ctx := context.Background()
	f := newApplyFixture(t, st,
		ProposalItem{Title: "Intake"},
		ProposalItem{Title: "Verification", ParentHint: "Intake"},
		ProposalItem{Title: "Handoff"})

	first, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID)
	if err != nil {
		t.Fatalf("first apply: %v", err)
	}
	if len(first) != 3 {
		t.Fatalf("first apply created %d nodes, want 3", len(first))
	}
	second, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID)
	if err != nil {
		t.Fatalf("second apply: %v", err)
	}
	if len(second) != 0 {
		t.Fatalf("second apply created %d nodes, want 0 (the items were already applied)", len(second))
	}
	byTitle := f.wantTitles(t, st, "Intake", "Verification", "Handoff")
	if p := byTitle["Verification"].ParentID; p == nil || *p != byTitle["Intake"].ID {
		t.Fatalf("Verification parent = %v, want the Intake node %s (parentHint)", p, byTitle["Intake"].ID)
	}
}

func TestProposalApply_ConcurrentAppliesCreateEachNodeOnce(t *testing.T) {
	st := newTestStore(t)
	ctx := context.Background()
	f := newApplyFixture(t, st,
		ProposalItem{Title: "Intake"},
		ProposalItem{Title: "Verification"},
		ProposalItem{Title: "Handoff"})

	const racers = 5
	var (
		wg      sync.WaitGroup
		gate    = make(chan struct{})
		mu      sync.Mutex
		created int
		errs    []error
	)
	for i := 0; i < racers; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			<-gate
			ids, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID)
			mu.Lock()
			defer mu.Unlock()
			created += len(ids)
			if err != nil {
				errs = append(errs, err)
			}
		}()
	}
	close(gate)
	wg.Wait()

	if len(errs) > 0 {
		t.Fatalf("concurrent applies failed: %v", errs)
	}
	if created != 3 {
		t.Fatalf("%d concurrent applies created %d nodes in total, want 3 (each item once)", racers, created)
	}
	f.wantTitles(t, st, "Intake", "Verification", "Handoff")
}

// poisonRoadmapTitle makes the database refuse one exact node title, so an
// apply can fail part-way through on a real constraint (see poisonTitleOn).
func poisonRoadmapTitle(t *testing.T, title string) (lift func()) {
	t.Helper()
	return poisonTitleOn(t, "roadmap_nodes", title)
}

// poisonTitleOn makes the database refuse one exact title in insideout.<table>,
// so a write can fail part-way through on a real constraint, no mock. The title
// must be generated by the caller (hex and hyphens only): DDL takes no bind
// parameters. The returned func lifts the poison; Cleanup lifts it too.
func poisonTitleOn(t *testing.T, table, title string) (lift func()) {
	t.Helper()
	ownerURL := os.Getenv("DATABASE_OWNER_URL")
	if ownerURL == "" {
		t.Skip("DATABASE_OWNER_URL not set, skipping the failure-injection check")
	}
	ctx := context.Background()
	owner, err := Open(ctx, ownerURL)
	if err != nil {
		t.Fatalf("open owner store: %v", err)
	}
	t.Cleanup(owner.Close)
	name := "rv4_poison_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	if _, err := owner.Pool.Exec(ctx, fmt.Sprintf(
		`ALTER TABLE insideout.%s ADD CONSTRAINT %s CHECK (title <> '%s') NOT VALID`, table, name, title)); err != nil {
		t.Fatalf("poison title: %v", err)
	}
	lift = func() {
		if _, err := owner.Pool.Exec(ctx, fmt.Sprintf(`ALTER TABLE insideout.%s DROP CONSTRAINT IF EXISTS %s`, table, name)); err != nil {
			t.Errorf("lift poison: %v", err)
		}
	}
	t.Cleanup(lift)
	return lift
}

func TestProposalApply_FailureRollsBackEveryNode(t *testing.T) {
	st := newTestStore(t)
	ctx := context.Background()
	poison := "poison-" + uuid.NewString()
	lift := poisonRoadmapTitle(t, poison)
	f := newApplyFixture(t, st,
		ProposalItem{Title: "Intake"},
		ProposalItem{Title: poison},
		ProposalItem{Title: "Handoff"})

	if ids, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID); err == nil {
		t.Fatalf("apply returned no error although the database refuses item 2 (created %d nodes)", len(ids))
	}
	// One transaction: item 1 must not survive item 2's failure.
	f.wantTitles(t, st)

	lift()
	ids, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID)
	if err != nil {
		t.Fatalf("retry after the cause is gone: %v", err)
	}
	if len(ids) != 3 {
		t.Fatalf("retry created %d nodes, want all 3 (the failed apply must claim nothing)", len(ids))
	}
	f.wantTitles(t, st, "Intake", poison, "Handoff")
}

// Green-only guard (the applied_at column did not exist at the base). A
// workspace admin who does not own the project is a plan writer, so their
// accept must apply the proposal, and the items they applied stay applied for
// the owner who accepts next. The claim is an RLS-filtered UPDATE: lose the
// admin arm of item_applier_update and it matches no row for the admin, which
// reads as "already applied", so the accept would answer 200 and build nothing.
func TestProposalApply_ANonOwnerWorkspaceAdminAppliesOnceAcrossActors(t *testing.T) {
	st := newTestStore(t)
	ctx := context.Background()
	f := newApplyFixture(t, st, ProposalItem{Title: "Intake"}, ProposalItem{Title: "Handoff"})
	admin := mkUser(t, st)
	if _, err := st.JoinWorkspace(ctx, admin.ID, f.ws.Code); err != nil {
		t.Fatalf("join: %v", err)
	}
	if err := st.UpdateMemberRole(ctx, f.owner.ID, f.ws.ID, admin.ID, "admin"); err != nil {
		t.Fatalf("make admin: %v", err)
	}

	_, ids, err := st.DecideAndApplyProposal(ctx, admin.ID, f.upd.ID, "accepted", "", true)
	if err != nil || len(ids) != 2 {
		t.Fatalf("admin accept: %d nodes, %v, want both items applied", len(ids), err)
	}
	f.wantTitles(t, st, "Intake", "Handoff")

	_, ids, err = st.DecideAndApplyProposal(ctx, f.owner.ID, f.upd.ID, "accepted", "", true)
	if err != nil || len(ids) != 0 {
		t.Fatalf("owner accept after the admin's: %d nodes, %v, want 0 (applied once across actors)", len(ids), err)
	}
	f.wantTitles(t, st, "Intake", "Handoff")
}

// rv4-FR-F38, F25: 20261018120000 added applied_at with no backfill, so a
// proposal the old build had applied (nodes built, applied_at NULL) built its
// nodes a second time on the next accept with apply. The upgrade step stamps an
// item only when its node demonstrably exists: an accepted decision, and a node
// of the same project whose description is the apply's own "proposed: <title>",
// each node credited to one item. The old shape is made the way it came to be,
// a real accept with apply, and the stamps are then wiped as the owner.
func TestRvStoreDbBackfill_AppliedBeforeTheColumnReadsAsApplied(t *testing.T) {
	st := newTestStore(t)
	owner := rvStoreDbOwnerStore(t)
	ctx := context.Background()
	decide := func(f *applyFixture, decision string, apply bool) int {
		t.Helper()
		_, ids, err := st.DecideAndApplyProposal(ctx, f.owner.ID, f.upd.ID, decision, "", apply)
		if err != nil {
			t.Fatalf("%s (apply=%v): %v", decision, apply, err)
		}
		return len(ids)
	}
	// Project 1: the applied proposal; one rejected before it (it would take the
	// node's credit if the decision were ignored); one accepted after it with no
	// node of its own (same title, one node: one stamp).
	applied := newApplyFixture(t, st, ProposalItem{Title: "Intake"}, ProposalItem{Title: "Verification", ParentHint: "Intake"}, ProposalItem{Title: "Handoff"})
	rejected := rvStoreDbAnotherProposal(t, st, applied, "Intake")
	lateAccept := rvStoreDbAnotherProposal(t, st, applied, "Intake")
	decide(rejected, "rejected", false)
	if n := decide(applied, "accepted", true); n != 3 {
		t.Fatalf("the accept built %d nodes, want 3", n)
	}
	decide(lateAccept, "accepted", false)
	// Project 2: accepted without apply (nothing built); one title has a node made
	// by hand, which carries no "proposed:" mark; "Later A" was then built by a
	// proposal the new build applied (stamped, never wiped), so that node is spoken for.
	waiting := newApplyFixture(t, st, ProposalItem{Title: "Later A"}, ProposalItem{Title: "Later B"}, ProposalItem{Title: "Handmade"})
	if _, err := st.CreateRoadmapNode(ctx, waiting.owner.ID, waiting.proj.ID, nil, "Handmade", ""); err != nil {
		t.Fatalf("hand-made node: %v", err)
	}
	decide(waiting, "accepted", false)
	built := rvStoreDbAnotherProposal(t, st, waiting, "Later A")
	decide(built, "accepted", true)
	// Project 3: another project's applied "Later A", whose mark must not count here.
	elsewhere := newApplyFixture(t, st, ProposalItem{Title: "Later A"})
	decide(elsewhere, "accepted", true)

	for _, f := range []*applyFixture{applied, elsewhere} { // the old build never remembered
		if _, err := owner.Pool.Exec(ctx, `UPDATE insideout.proposal_items SET applied_at = NULL WHERE update_id = $1`, f.upd.ID); err != nil {
			t.Fatalf("wipe the stamps: %v", err)
		}
	}
	rvStoreDbBackfill(t, owner)

	for _, c := range []struct {
		what           string
		f              *applyFixture
		stamped, total int
	}{
		{"applied before the column existed", applied, 3, 3},
		{"another project's applied proposal", elsewhere, 1, 1},
		{"rejected, same title as an applied item", rejected, 0, 1},
		{"accepted later, same title, no node of its own", lateAccept, 0, 1},
		{"accepted without apply (a hand-made node, another project's mark, a stamped twin)", waiting, 0, 3},
		{"applied by the new build, never wiped", built, 1, 1},
	} {
		if stamped, total := rvStoreDbStamped(t, owner, c.f.upd.ID); stamped != c.stamped || total != c.total {
			t.Errorf("%s: %d of %d items stamped, want %d of %d", c.what, stamped, total, c.stamped, c.total)
		}
	}
	var atDecision bool
	if err := owner.Pool.QueryRow(ctx, `
		SELECT bool_and(i.applied_at = d.decided_at) FROM insideout.proposal_items i
		JOIN insideout.proposal_decisions d USING (update_id) WHERE update_id = $1`, applied.upd.ID).Scan(&atDecision); err != nil || !atDecision {
		t.Errorf("the stamps should carry the decision time (err %v, match %v)", err, atDecision)
	}

	all := []uuid.UUID{applied.upd.ID, rejected.upd.ID, lateAccept.upd.ID, waiting.upd.ID, built.upd.ID, elsewhere.upd.ID}
	before := rvStoreDbAppliedAt(t, owner, all...)
	rvStoreDbBackfill(t, owner)
	for id, at := range rvStoreDbAppliedAt(t, owner, all...) {
		if before[id] != at {
			t.Errorf("a second run moved item %s: applied_at %q -> %q", id, before[id], at)
		}
	}

	// The point of it: accepting again builds only what was never built.
	for _, f := range []*applyFixture{applied, elsewhere} {
		if n := decide(f, "accepted", true); n != 0 {
			t.Errorf("accepting an upgraded proposal again built %d nodes, want 0", n)
		}
	}
	if n := decide(lateAccept, "accepted", true); n != 1 {
		t.Errorf("the late proposal built %d nodes, want 1 (it never built its own)", n)
	}
	applied.wantTitles(t, st, "Intake", "Intake", "Verification", "Handoff")
	if n := decide(waiting, "accepted", true); n != 3 {
		t.Errorf("the proposal accepted without apply built %d nodes, want 3", n)
	}
	waiting.wantTitles(t, st, "Handmade", "Handmade", "Later A", "Later A", "Later B")
}
