// rv4-FEAT-02: accepting a proposal applies its items once. Real PostgreSQL
// (DATABASE_URL); the failure case also needs DATABASE_OWNER_URL, because
// poisoning one title is the only way to make the database itself refuse an
// insert part-way through an apply without a mock.

// applyFixture is a project whose owner filed an agent proposal carrying items.
type applyFixture struct {
	owner *User
	ws    *Workspace
	proj  *Project
	upd   *ProjectUpdate
}

func newApplyFixture(t *testing.T, st *Store, items ...ProposalItem) *applyFixture {
	t.Helper()
	ctx := context.Background()
	owner := mkUser(t, st)
	ws, err := st.CreateWorkspace(ctx, owner.ID, "Apply once WS", "")
	if err != nil {
		t.Fatalf("create workspace: %v", err)
	}
	proj, err := st.CreateProject(ctx, owner.ID, ws.ID, "Apply once", "")
	if err != nil {
		t.Fatalf("create project: %v", err)
	}
	upd, err := st.AddProjectUpdate(ctx, owner.ID, proj.ID, "agent_proposal", "[agent proposal/structure] apply once")
	if err != nil {
		t.Fatalf("add proposal: %v", err)
	}
	for i := range items {
		items[i].Action = "add_node"
	}
	if err := st.AddProposalItems(ctx, owner.ID, upd.ID, items); err != nil {
		t.Fatalf("add items: %v", err)
	}
	return &applyFixture{owner: owner, ws: ws, proj: proj, upd: upd}
}

// nodes returns the project's roadmap nodes keyed by title, failing on a title
// that appears twice: a second apply is exactly that.
func (f *applyFixture) nodes(t *testing.T, st *Store) (map[string]RoadmapNode, []string) {
	t.Helper()
	list, err := st.ListRoadmap(context.Background(), f.owner.ID, f.proj.ID)
	if err != nil {
		t.Fatalf("list roadmap: %v", err)
	}
	byTitle := map[string]RoadmapNode{}
	titles := make([]string, 0, len(list))
	for _, n := range list {
		byTitle[n.Title] = n
		titles = append(titles, n.Title)
	}
	sort.Strings(titles)
	return byTitle, titles
}

func (f *applyFixture) wantTitles(t *testing.T, st *Store, want ...string) map[string]RoadmapNode {
	t.Helper()
	byTitle, got := f.nodes(t, st)
	sort.Strings(want)
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Fatalf("roadmap nodes: got %q, want %q", got, want)
	}
	return byTitle
}

func TestProposalApply_SecondApplyCreatesNothing(t *testing.T) {
	st := newTestStore(t)
	ctx := context.Background()
	f := newApplyFixture(t, st,
		ProposalItem{Title: "Intake"},
		ProposalItem{Title: "Verification", ParentHint: "Intake"},
		ProposalItem{Title: "Handoff"})

	first, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID)
	if err != nil {
		t.Fatalf("first apply: %v", err)
	}
	if len(first) != 3 {
		t.Fatalf("first apply created %d nodes, want 3", len(first))
	}
	second, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID)
	if err != nil {
		t.Fatalf("second apply: %v", err)
	}
	if len(second) != 0 {
		t.Fatalf("second apply created %d nodes, want 0 (the items were already applied)", len(second))
	}
	byTitle := f.wantTitles(t, st, "Intake", "Verification", "Handoff")
	if p := byTitle["Verification"].ParentID; p == nil || *p != byTitle["Intake"].ID {
		t.Fatalf("Verification parent = %v, want the Intake node %s (parentHint)", p, byTitle["Intake"].ID)
	}
}

func TestProposalApply_ConcurrentAppliesCreateEachNodeOnce(t *testing.T) {
	st := newTestStore(t)
	ctx := context.Background()
	f := newApplyFixture(t, st,
		ProposalItem{Title: "Intake"},
		ProposalItem{Title: "Verification"},
		ProposalItem{Title: "Handoff"})

	const racers = 5
	var (
		wg      sync.WaitGroup
		gate    = make(chan struct{})
		mu      sync.Mutex
		created int
		errs    []error
	)
	for i := 0; i < racers; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			<-gate
			ids, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID)
			mu.Lock()
			defer mu.Unlock()
			created += len(ids)
			if err != nil {
				errs = append(errs, err)
			}
		}()
	}
	close(gate)
	wg.Wait()

	if len(errs) > 0 {
		t.Fatalf("concurrent applies failed: %v", errs)
	}
	if created != 3 {
		t.Fatalf("%d concurrent applies created %d nodes in total, want 3 (each item once)", racers, created)
	}
	f.wantTitles(t, st, "Intake", "Verification", "Handoff")
}

// poisonRoadmapTitle makes the database refuse one exact node title, so an
// apply can fail part-way through on a real constraint. The title must be
// generated by the caller (hex and hyphens only): DDL takes no bind
// parameters. The returned func lifts the poison; Cleanup lifts it too.
func poisonRoadmapTitle(t *testing.T, title string) (lift func()) {
	t.Helper()
	ownerURL := os.Getenv("DATABASE_OWNER_URL")
	if ownerURL == "" {
		t.Skip("DATABASE_OWNER_URL not set, skipping the failure-injection check")
	}
	ctx := context.Background()
	owner, err := Open(ctx, ownerURL)
	if err != nil {
		t.Fatalf("open owner store: %v", err)
	}
	t.Cleanup(owner.Close)
	name := "rv4_poison_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	if _, err := owner.Pool.Exec(ctx, fmt.Sprintf(
		`ALTER TABLE insideout.roadmap_nodes ADD CONSTRAINT %s CHECK (title <> '%s') NOT VALID`, name, title)); err != nil {
		t.Fatalf("poison title: %v", err)
	}
	lift = func() {
		if _, err := owner.Pool.Exec(ctx, `ALTER TABLE insideout.roadmap_nodes DROP CONSTRAINT IF EXISTS `+name); err != nil {
			t.Errorf("lift poison: %v", err)
		}
	}
	t.Cleanup(lift)
	return lift
}

func TestProposalApply_FailureRollsBackEveryNode(t *testing.T) {
	st := newTestStore(t)
	ctx := context.Background()
	poison := "poison-" + uuid.NewString()
	lift := poisonRoadmapTitle(t, poison)
	f := newApplyFixture(t, st,
		ProposalItem{Title: "Intake"},
		ProposalItem{Title: poison},
		ProposalItem{Title: "Handoff"})

	if ids, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID); err == nil {
		t.Fatalf("apply returned no error although the database refuses item 2 (created %d nodes)", len(ids))
	}
	// One transaction: item 1 must not survive item 2's failure.
	f.wantTitles(t, st)

	lift()
	ids, err := st.ApplyProposalItemsForUpdate(ctx, f.owner.ID, f.upd.ID)
	if err != nil {
		t.Fatalf("retry after the cause is gone: %v", err)
	}
	if len(ids) != 3 {
		t.Fatalf("retry created %d nodes, want all 3 (the failed apply must claim nothing)", len(ids))
	}
	f.wantTitles(t, st, "Intake", poison, "Handoff")
}
